import { EXPORT_SLUG_FALLBACK } from '@/constants/storage';

export function toSlug(value: string): string {
  const slug = value
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60)
    .replace(/-+$/g, '');
  return slug || EXPORT_SLUG_FALLBACK;
}
